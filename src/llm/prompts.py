from typing import List, Optional
from src.config import CURRENT_COMPLIANCE_YEAR


def build_image_evidence_prompt(
    standard_id: Optional[str] = None,
    standard_title: Optional[str] = None,
) -> str:
    control_line = (
        f"المعيار المطلوب التحقق من مطابقة الدليل له هو ({standard_id}) \"{standard_title}\".\n"
        if standard_id and standard_title
        else "لا يوجد معيار محدد بعد؛ صف الدليل بشكل عام.\n"
    )
    return (
        "افحص لقطة الشاشة/الصورة المرفقة كدليل إثبات لتدقيق امتثال.\n"
        f"{control_line}"
        "اكتب إجابة منظمة تشمل:\n"
        "1. وصف محتوى الصورة (نوع المستند/الشاشة، النظام الظاهر، البيانات الرئيسية).\n"
        "2. هل تُعد هذه الصورة نوع دليل مناسب ومطابق لمتطلبات المعيار المذكور أعلاه؟ (نعم/جزئياً/لا) مع التبرير.\n"
        f"3. هل يظهر في الصورة تاريخ أو طابع زمني؟ إن وُجد اذكره بالضبط، وحدد صراحة هل هو ضمن عام {CURRENT_COMPLIANCE_YEAR} "
        f"(يُعتبر دليلاً محدثاً لقياس الامتثال الحالي) أم أنه أقدم من ذلك (يُعتبر دليلاً غير محدث وغير كافٍ لإثبات الامتثال الحالي). "
        "إذا لم يظهر أي تاريخ في الصورة، فقل ذلك بوضوح ونبّه إلى أن غياب التاريخ يضعف قيمة الدليل.\n"
        "4. أي ملاحظات إضافية تؤثر على قبول الدليل."
    )


def build_audit_prompt(
    proposal_text: str,
    evidence: List[dict],
    standard_id: Optional[str] = None,
    standard_title: Optional[str] = None,
    framework_label: Optional[str] = None,
) -> str:
    evidence_text = "\n\n".join(
        [f"- {item['source']}: {item['text']}" for item in evidence]
    )
    framework_name = framework_label or "الإطار التنظيمي المحدد"

    if standard_id and standard_title:
        focus_instruction = (
            f"راجع الوثيقة والأدلة المصورة المرفقة (إن وُجدت) وقارن محتواها حصريًا مع متطلبات المعيار/الضابط رقم "
            f"({standard_id}) \"{standard_title}\" من {framework_name}، "
            f"مستندًا فقط إلى نص هذا المعيار الوارد في الأدلة المسترجعة أدناه.\n"
        )
        output_instructions = (
            "اكتب مخرجات منظمة تشمل:\n"
            f"1. نص هدف المعيار/الضابط ({standard_id}) كما ورد في الأدلة.\n"
            "2. تقييم درجة الامتثال لهذا المعيار تحديدًا (كلي / جزئي / لا يوجد التزام).\n"
            "3. المتطلبات التي تحقّقت وأين ظهرت في الوثيقة أو الأدلة المصورة.\n"
            "4. الفجوات: المتطلبات الناقصة أو غير المدعومة بدليل كافٍ أو محدّث.\n"
            "5. توصيات محددة لسد الفجوات وتحقيق الامتثال الكامل لهذا المعيار.\n"
        )
    else:
        focus_instruction = (
            "راجع النص التالي والأدلة المصورة المرفقة (إن وُجدت) وقارن محتواها مع متطلبات الامتثال المتوفرة.\n"
        )
        output_instructions = (
            "اكتب مخرجات منظمة تشمل:\n"
            "1. تقييم عام للامتثال.\n"
            "2. النقاط التي تفي بالمتطلبات.\n"
            "3. النقاط الناقصة أو المخاطر.\n"
            "4. توصيات التحسين.\n"
            "5. قائمة بالمصادر المستند إليها.\n"
        )

    return (
        f"{focus_instruction}"
        f"{output_instructions}\n"
        "ملاحظة هامة: إذا كانت الوثيقة تتضمن قسمًا بعنوان \"تحليل الأدلة المصورة المرفقة\"، اعتبره جزءًا من الأدلة المقدَّمة، "
        f"وإذا ذُكر فيه أن تاريخ الدليل المصور أقدم من العام {CURRENT_COMPLIANCE_YEAR} أو أنه لا يحمل تاريخًا واضحًا، "
        "فيجب اعتبار هذا الدليل غير كافٍ لإثبات الامتثال الحالي والتنويه بذلك صراحة ضمن الفجوات.\n\n"
        f"نص الوثيقة المرفوعة (شامل تحليل أي أدلة مصورة):\n{proposal_text}\n\n"
        f"الأدلة المسترجعة من قاعدة المعرفة:\n{evidence_text}\n\n"
        f"إذا لم توجد معلومات كافية في الأدلة، فقل بوضوح أن النتائج غير مؤكدة وأن الحالات غير المدعومة يجب التحقق منها."
    )
